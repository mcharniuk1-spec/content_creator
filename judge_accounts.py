def push(con):
    import notion
    db = notion.env('NOTION_ACCOUNTS_DB')
    have, cur = {}, None
    while True:
        body = {'page_size': 100}
        if cur:
            body['start_cursor'] = cur
        res = notion.call('POST', f'/databases/{db}/query', body)
        for p in res['results']:
            t = p['properties']['Account']['title']
            if t:
                have[t[0]['plain_text']] = p['id']
        cur = res.get('next_cursor')
        if not cur:
            break
    n = 0
    for user, pid in have.items():
        verdict, text = JUDGED.get(user, ('watch', ''))
        notion.call('PATCH', f'/pages/{pid}', {'properties': {
            'Verdict': {'select': {'name': verdict}},
            'What to borrow': {'rich_text': [{'text': {'content': text[:1900]}}]}}})
        n += 1
    print(f'решение проставлено по {n} аккаунтам, из них разобрано вручную: {len(JUDGED)}')
    return n


if __name__ == '__main__':
    con = connect()
    if '--push' in sys.argv:
        push(con)
    else:
        for u, (v, t) in JUDGED.items():
            print(f'\n{u} — {v}\n  {t}')
